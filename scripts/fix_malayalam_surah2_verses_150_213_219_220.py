def print_rows(cur, label):
    print(label)
    for row in cur.execute(
        "SELECT id, verse_number, malayalam_translation "
        "FROM malayalam_verses "
        "WHERE surah_id = 2 AND verse_number IN (150, 213, 219, 220) "
        "ORDER BY verse_number"
    ):
        print(row)


conn = sqlite3.connect(DB)
cur = conn.cursor()

print_rows(cur, "Before - surah 2 verses 150, 213, 219, 220:")

cur.execute(
    "UPDATE malayalam_verses SET malayalam_translation = ? "
    "WHERE surah_id = 2 AND verse_number = 213",
    (V213,),
)


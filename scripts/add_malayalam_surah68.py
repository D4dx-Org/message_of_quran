def insert_into(db_path):
    conn = sqlite3.connect(db_path)
    cur = conn.cursor()

    has_surah_number = any(
        row[1] == "surah_number"
        for row in cur.execute("PRAGMA table_info(malayalam_footnotes)")
    )

    cur.execute("DELETE FROM malayalam_surahs WHERE chapter_number = ?", (CHAPTER,))
    cur.execute("DELETE FROM malayalam_verses WHERE surah_id = ?", (CHAPTER,))
    if has_surah_number:
        cur.execute(
            "DELETE FROM malayalam_footnotes WHERE surah_number = ?", (CHAPTER,)
        )

    max_surah_id = cur.execute("SELECT MAX(id) FROM malayalam_surahs").fetchone()[0] or 0
    cur.execute(
        "INSERT INTO malayalam_surahs "
        "(id, chapter_number, arabic_name, malayalam_name, english_translation, "
        "revelation_period, introduction) VALUES (?, ?, ?, ?, ?, ?, ?)",
        (
            max_surah_id + 1,
            CHAPTER,
            ARABIC_NAME,
            MALAYALAM_NAME,
            ENGLISH_TRANSLATION,
            REVELATION_PERIOD,
            INTRODUCTION,
        ),
    )

    next_verse_id = cur.execute("SELECT MAX(id) FROM malayalam_verses").fetchone()[0] or 0
    for verse_number in sorted(VERSES):
        next_verse_id += 1
        cur.execute(
            "INSERT INTO malayalam_verses (id, surah_id, verse_number, malayalam_translation) "
            "VALUES (?, ?, ?, ?)",
            (next_verse_id, CHAPTER, verse_number, VERSES[verse_number]),
        )

    next_fn_id = cur.execute("SELECT MAX(id) FROM malayalam_footnotes").fetchone()[0] or 0
    for footnote_number in sorted(FOOTNOTES):
        next_fn_id += 1
        if has_surah_number:
            cur.execute(
                "INSERT INTO malayalam_footnotes (id, footnote_number, content, surah_number) "
                "VALUES (?, ?, ?, ?)",
                (next_fn_id, footnote_number, FOOTNOTES[footnote_number], CHAPTER),
            )
        else:
            cur.execute(
                "INSERT INTO malayalam_footnotes (id, footnote_number, content) "
                "VALUES (?, ?, ?)",
                (next_fn_id, footnote_number, FOOTNOTES[footnote_number]),
            )

    conn.commit()
    print(f"{db_path}: inserted surah {CHAPTER}, "
          f"{len(VERSES)} verses, {len(FOOTNOTES)} footnotes "
          f"(surah_number column: {has_surah_number})")
    conn.close()


if __name__ == "__main__":
    for path in sys.argv[1:]:
        insert_into(path)
